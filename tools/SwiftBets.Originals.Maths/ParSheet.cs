using System.Globalization;
using System.Text;
using System.Text.Json;
using SwiftBets.Originals.Domain.Slot;

namespace SwiftBets.Originals.Maths;

/// <summary>What the simulation measured, folded into the sheet: the parts the closed form cannot give.</summary>
public sealed record SimulationResult(long Rounds, double Rtp, double CiLow, double CiHigh, double CapEffect, double SigmaPerRound, long CappedRounds, double MaxRoundStakes);

/// <summary>Writes the PAR sheet (Markdown for people, CSV for spreadsheets) from the exact enumeration.</summary>
public static class ParSheet
{
    public static void Write(SlotGame slot, Rtp rtp, SimulationResult? sim, string markdownPath, string csvPath)
    {
        var game = slot.Definition;
        var md = new StringBuilder();
        var csv = new StringBuilder("section,key,value\n");
        void Row(string section, string key, string value) => csv.Append(CultureInfo.InvariantCulture, $"{section},{key},{value}\n");
        string P(double x) => x.ToString("P4", CultureInfo.InvariantCulture);

        md.AppendLine(CultureInfo.InvariantCulture, $"# {slot.Profile.Name}: PAR sheet");
        md.AppendLine();
        md.AppendLine("Generated by `tools/SwiftBets.Originals.Maths par` from the production game definition. Do not edit by hand.");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Definition hash: {DefinitionHash.Of(game)}");
        md.AppendLine();
        md.AppendLine("## Return to player");
        md.AppendLine();
        md.AppendLine("| | RTP | exact |");
        md.AppendLine("|---|---|---|");
        md.AppendLine(CultureInfo.InvariantCulture, $"| Base game | {P(rtp.BaseRtp)} | {Rtp.Fraction(rtp.Base.TotalUnits, rtp.Base.Cycle * game.LineCount)} |");
        md.AppendLine(CultureInfo.InvariantCulture, $"| Free spins | {P(rtp.FeatureRtp)} | {(rtp.Exact ? "closed form, below" : $"simulated, ± {P(rtp.FeatureRtpHalfWidth)} (99%)")} |");
        md.AppendLine(CultureInfo.InvariantCulture, $"| **Total (uncapped)** | **{P(rtp.Total)}** | |");
        if (sim is not null)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"| Cap effect | −{P(sim.CapEffect)} | simulation |");
            md.AppendLine(CultureInfo.InvariantCulture, $"| **Total (as played)** | **{P(rtp.Total - sim.CapEffect)}** | |");
        }

        Row("rtp", "base", rtp.BaseRtp.ToString("R", CultureInfo.InvariantCulture));
        Row("rtp", "feature", rtp.FeatureRtp.ToString("R", CultureInfo.InvariantCulture));
        Row("rtp", "total", rtp.Total.ToString("R", CultureInfo.InvariantCulture));

        md.AppendLine();
        md.AppendLine("## How the RTP is computed");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Each reel stop is drawn uniformly and independently (OS CSPRNG, `RandomNumberGenerator.GetInt32`). The base reels give a cycle of {rtp.Base.Cycle:N0} equally likely stop combinations; every one is evaluated with the production evaluator and its win summed exactly in line-bet units (stake = {game.LineCount} line bets).");
        md.AppendLine();
        md.AppendLine("- Base RTP = Σ wins / (cycle × lines).");
        md.AppendLine(CultureInfo.InvariantCulture, $"- P(trigger) = {rtp.Base.Triggers:N0} / {rtp.Base.Cycle:N0} = 1 in {1 / rtp.TriggerProbability:F2}.");
        if (rtp.Simulated is { } fv)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"- Split symbols that land in free spins lock in place for the rest of the feature, so one free spin depends on the ones before it and the feature cannot be enumerated. Its value is measured instead: {fv.Features:N0} whole features played through the production engine and RNG, without the cap.");
            md.AppendLine(CultureInfo.InvariantCulture, $"- Feature value V = {fv.MeanUnits / game.LineCount:F4} ± {fv.HalfWidthUnits / game.LineCount:F4} stakes (99% confidence; σ {fv.SigmaUnits / game.LineCount:F2} stakes per feature), {fv.MeanSpins:F2} spins per feature.");
        }
        else
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"- Over the free-spin reels (cycle {rtp.Free.Cycle:N0}, every win ×{game.FreeSpinMultiplier}): w = {rtp.WinPerFreeSpin / game.LineCount:F6} stakes per free spin; r = {rtp.RetriggerSpinsPerSpin:F6} extra spins awarded per free spin.");
            md.AppendLine(CultureInfo.InvariantCulture, $"- Expected spins per feature N = {game.FreeSpinsAwarded} / (1 − r) = {rtp.ExpectedFreeSpins:F6}; feature value V = w × N = {rtp.FeatureValueUnits / game.LineCount:F4} stakes.");
        }

        md.AppendLine("- Feature RTP = P(trigger) × V. Total = base + feature.");
        md.AppendLine(CultureInfo.InvariantCulture, $"- The {game.MaxWinStakes:N0}× cap applies to a base spin plus its feature; its small effect is measured by the simulation.");

        md.AppendLine();
        md.AppendLine("## Frequencies and volatility");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"- Hit frequency (base spin wins anything): {P(rtp.HitFrequency)} (1 in {1 / rtp.HitFrequency:F2}).");
        md.AppendLine(CultureInfo.InvariantCulture, $"- Feature frequency: 1 in {1 / rtp.TriggerProbability:F2} base spins; average {rtp.ExpectedFreeSpins:F2} spins worth {rtp.FeatureValueUnits / game.LineCount:F2}× stake.");
        md.AppendLine(CultureInfo.InvariantCulture, $"- Standard deviation of a base spin (exact): {rtp.BaseSigma:F4} stakes.");
        var maxBase = rtp.Base.CountByWinUnits.Keys.Max();
        md.AppendLine(CultureInfo.InvariantCulture, $"- Largest single base-spin win: {(double)maxBase / game.LineCount:F2}× stake ({rtp.Base.CountByWinUnits[maxBase]:N0} of {rtp.Base.Cycle:N0} combinations).");
        if (sim is not null)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"- Standard deviation per round incl. feature (simulation): {sim.SigmaPerRound:F4} stakes.");
            md.AppendLine(CultureInfo.InvariantCulture, $"- Rounds reaching the {game.MaxWinStakes:N0}× cap: {sim.CappedRounds:N0} of {sim.Rounds:N0}; largest round seen {sim.MaxRoundStakes:F2}× stake.");
        }

        md.AppendLine();
        md.AppendLine("Base-spin win distribution (stakes):");
        md.AppendLine();
        md.AppendLine("| win | probability |");
        md.AppendLine("|---|---|");
        double[] bands = [0, 0.000001, 1, 2, 5, 10, 20, 50, 100, 250, double.MaxValue];
        for (var i = 0; i < bands.Length - 1; i++)
        {
            double p = 0;
            foreach (var (units, count) in rtp.Base.CountByWinUnits)
            {
                var x = (double)units / game.LineCount;
                if (x >= bands[i] && x < bands[i + 1])
                {
                    p += (double)count / (double)rtp.Base.Cycle;
                }
            }

            var label = i == 0 ? "0" : bands[i + 1] == double.MaxValue ? $"≥ {bands[i]}" : $"{(i == 1 ? "> 0" : bands[i].ToString(CultureInfo.InvariantCulture))} to < {bands[i + 1]}";
            md.AppendLine(CultureInfo.InvariantCulture, $"| {label} | {p:P4} |");
        }

        md.AppendLine();
        md.AppendLine("## Contribution to RTP");
        md.AppendLine();
        md.AppendLine(rtp.Exact ? "| pay | base | free spins (per trigger, weighted) |" : "| pay | base | free-spin reels without locks (for reference) |");
        md.AppendLine("|---|---|---|");
        var keys = rtp.Base.UnitsBySymbolAndCount.Keys.Union(rtp.Free.UnitsBySymbolAndCount.Keys).OrderBy(k => k, StringComparer.Ordinal);
        foreach (var key in keys)
        {
            var b = (double)rtp.Base.UnitsBySymbolAndCount.GetValueOrDefault(key) / ((double)rtp.Base.Cycle * game.LineCount);
            var f = (double)rtp.Free.UnitsBySymbolAndCount.GetValueOrDefault(key) / (double)rtp.Free.Cycle * rtp.ExpectedFreeSpins * rtp.TriggerProbability / game.LineCount;
            md.AppendLine(CultureInfo.InvariantCulture, $"| {Label(key)} | {P(b)} | {P(f)} |");
            Row("contribution", key, $"{b.ToString("R", CultureInfo.InvariantCulture)};{f.ToString("R", CultureInfo.InvariantCulture)}");
        }

        md.AppendLine();
        md.AppendLine("## Pay table");
        md.AppendLine();
        var wild = game.Symbols.Select((s, i) => (s, i)).Where(x => x.s.Kind == SymbolKind.Wild).Select(x => (byte)x.i).ToHashSet();
        var wildReels = string.Join(", ", Enumerable.Range(0, 5).Where(r => game.BaseReels[r].Any(wild.Contains)).Select(r => r + 1));
        var splits = game.Symbols.Any(s => s.Weight > 1);
        md.AppendLine(CultureInfo.InvariantCulture, $"Line pays in line bets (stake / {game.LineCount}), for one symbol running over at least three adjacent reels from reel 1; Wild (reels {wildReels}) substitutes for all but Scatter and does not pay alone;{(splits ? " split symbols count as their weight and pay as their single, and the pay is for the run's total count (a count above the last column pays the last);" : "")} highest win per line; line and scatter wins add.");
        md.AppendLine();
        var columns = game.LinePays.Values.Max(p => p.Length);
        md.Append("| symbol |").AppendJoin("", Enumerable.Range(3, columns).Select(c => $" {c} |")).AppendLine();
        md.Append("|---|").AppendJoin("", Enumerable.Repeat("---|", columns)).AppendLine();
        foreach (var (symbol, pays) in game.LinePays.OrderBy(p => p.Key))
        {
            md.Append(CultureInfo.InvariantCulture, $"| {game.Name(symbol)} |").AppendJoin("", Enumerable.Range(0, columns).Select(c => c < pays.Length ? $" {pays[c]} |" : " |")).AppendLine();
        }

        md.Append("| Scatter (× total stake, anywhere) |").AppendJoin("", Enumerable.Range(0, columns).Select(c => c < 3 ? $" {game.ScatterPays[c]} |" : " |")).AppendLine();
        if (splits)
        {
            md.AppendLine();
            md.AppendLine("Symbols: " + string.Join("; ", game.Symbols.Select(s => $"{s.Name} ({s.Kind.ToString().ToLowerInvariant()}{(s.Weight > 1 ? $", counts {s.Weight}" : "")}{(s.PaysAs is { } p ? $", pays as {p}" : "")})")) + ".");
        }

        md.AppendLine();
        var feature = game.Feature;
        md.AppendLine(CultureInfo.InvariantCulture, $"3 or more Scatters award {feature.Awarded} free spins on the free-spin reels; every free-spin win ×{feature.Multiplier}; {(feature.Retrigger ? $"3 or more Scatters during free spins award {feature.Awarded} more" : "free spins cannot be retriggered")}{(feature.LockSplits ? "; every split symbol that lands in a free spin locks in place for the rest of the feature" : "")}. Max win {game.MaxWinStakes:N0}× stake per round.");

        md.AppendLine();
        md.AppendLine("## Paylines (row per reel, 0 = top)");
        md.AppendLine();
        for (var i = 0; i < game.Lines.Count; i++)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"{i + 1}. {string.Join(" ", game.Lines[i])}");
        }

        Strips("Base reel strips", game.BaseReels);
        Strips("Free-spin reel strips", game.FreeReels);
        File.WriteAllText(markdownPath, md.ToString());
        File.WriteAllText(csvPath, csv.ToString());

        void Strips(string title, IReadOnlyList<IReadOnlyList<byte>> reels)
        {
            md.AppendLine();
            md.AppendLine(CultureInfo.InvariantCulture, $"## {title} (stop 0 first; the window shows a stop and the next two, wrapping)");
            md.AppendLine();
            for (var r = 0; r < reels.Count; r++)
            {
                var counts = reels[r].GroupBy(s => s).OrderBy(g => g.Key).Select(g => $"{game.Name(g.Key)} {g.Count()}");
                var names = reels[r].Select(game.Name);
                md.AppendLine(CultureInfo.InvariantCulture, $"- Reel {r + 1} ({reels[r].Count} stops; {string.Join(", ", counts)}): {string.Join(" ", names)}");
                Row(title.StartsWith("Base", StringComparison.Ordinal) ? "base_strip" : "free_strip", $"reel{r + 1}", string.Join(' ', names));
            }
        }
    }

    /// <summary>"Lion:05" as "Lion × 5".</summary>
    private static string Label(string key) => key.Split(':') is [var name, var count] ? $"{name} × {int.Parse(count, CultureInfo.InvariantCulture)}" : key;

    public static SimulationResult? ReadSimulation(string[] args) =>
        Array.IndexOf(args, "--with-simulation") is var at and >= 0
            ? JsonSerializer.Deserialize<SimulationResult>(File.ReadAllText(args[at + 1]))
            : null;
}
