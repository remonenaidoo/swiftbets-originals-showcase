using System.Globalization;
using System.Text;
using SwiftBets.Originals.Domain.Instant;

namespace SwiftBets.Originals.Maths;

/// <summary>Maths documents for the six instant games added on 2026-10-19: exact, from the production rules.</summary>
public static class SixSheets
{
    private static string Head(string name, string rule) =>
        $"# {name}: maths document\n\nGenerated by `tools/SwiftBets.Originals.Maths six` from the production rules. Do not edit by hand.\n\n## The rule\n\n{rule}\n\n";

    private static string X(long bp) => (bp / (double)Mult.One).ToString("0.####", CultureInfo.InvariantCulture) + "×";

    public static int Write(string dir)
    {
        var ok = true;

        // Sunburst Wheel: each segment equally likely, so the RTP is the wheel's mean.
        var wheel = new StringBuilder(Head("Sunburst Wheel", "The round's first float × segments, floored, picks one of 10, 20 or 30 equal segments, which pays its multiplier. RTP = the mean of the wheel's segments."));
        wheel.AppendLine("| wheel | segments, clockwise from the top | RTP |").AppendLine("|---|---|---|");
        foreach (var ((segments, risk), table) in WheelTables.Wheels)
        {
            var rtp = table.Sum() / (double)segments / Mult.One;
            wheel.AppendLine(CultureInfo.InvariantCulture, $"| {segments}, {risk} | {string.Join(" · ", table.Select(X))} | {rtp:P4} |");
            ok &= rtp <= 0.96 + 1e-12;
        }

        File.WriteAllText($"{dir}/sunburst-wheel.md", wheel.ToString());

        // Coin Flip: P(at least k of n) = ways / 2^n; pay floor(9,600 × 2^n / ways) bp.
        var coins = new StringBuilder(Head("Coin Flip", "Each coin lands on heads when its float is below 0.5. With n coins and at least k needed on the chosen side, P = Σ_{j≥k} C(n, j) / 2^n and the pay is 0.96 ÷ P, floored to 0.0001×. RTP = P × pay."));
        coins.AppendLine("| coins | need | pays | RTP |").AppendLine("|---|---|---|---|");
        double cLo = 1, cHi = 0;
        for (var n = 1; n <= 10; n++)
        {
            for (var k = 1; k <= n; k++)
            {
                var bp = CoinFlip.MultiplierBp(n, k);
                var rtp = CoinFlip.Ways(n, k) / Math.Pow(2, n) * bp / Mult.One;
                cLo = Math.Min(cLo, rtp); cHi = Math.Max(cHi, rtp);
                if (n is 1 or 2 or 5 or 10) coins.AppendLine(CultureInfo.InvariantCulture, $"| {n} | {k} | {X(bp)} | {rtp:P4} |");
            }
        }

        coins.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"Over all 55 choices (1–10 coins, any need) the RTP is between {cLo:P4} and {cHi:P4}.");
        File.WriteAllText($"{dir}/coin-flip.md", coins.ToString());
        ok &= cHi <= 0.96 + 1e-12;

        // Lucky Scratch: fixed odds in 100,000.
        var scratch = new StringBuilder(Head("Lucky Scratch", "The round's first float × 100,000, floored, picks the prize from fixed bands (below); the card is then laid out so the prize shows exactly three times and nothing else more than twice."));
        scratch.AppendLine("| prize | pays | chance | RTP share |").AppendLine("|---|---|---|---|");
        double sRtp = 0;
        foreach (var (p, i) in LuckyScratch.Prizes.Select((p, i) => (p, i)))
        {
            var share = p.Chance / (double)LuckyScratch.OddsScale * p.PayBp / Mult.One;
            sRtp += share;
            scratch.AppendLine(CultureInfo.InvariantCulture, $"| {i + 1} | {X(p.PayBp)} | {p.Chance} in {LuckyScratch.OddsScale:N0} | {share:P4} |");
        }

        var hit = LuckyScratch.Prizes.Sum(p => p.Chance) / (double)LuckyScratch.OddsScale;
        scratch.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"**RTP {sRtp:P4}**, a win on {hit:P2} of cards.");
        // The layout: no losing or winning card ever shows a second triple (checked over many seeded cards).
        var rng = new Random(11);
        for (var t = 0; t < 200_000; t++)
        {
            var f = Enumerable.Range(0, LuckyScratch.Floats).Select(_ => rng.NextDouble()).ToArray();
            var prize = LuckyScratch.Prize(f[0]);
            var cells = LuckyScratch.Card(prize, f);
            ok &= cells.GroupBy(c => c).All(g => g.Count() <= 2 || (g.Key == prize && g.Count() == 3)) && (prize == 0 || cells.Count(c => c == prize) == 3);
        }

        scratch.AppendLine().AppendLine("200,000 seeded cards were laid out and checked: every winning card shows its prize exactly three times, and no card shows any other symbol three times.");
        File.WriteAllText($"{dir}/lucky-scratch.md", scratch.ToString());
        ok &= sRtp <= 0.96 + 1e-12;

        // Gem Hand: all 7^5 hands, each equally likely, through the production classifier.
        var counts = new Dictionary<string, int>();
        for (var h = 0; h < 16_807; h++)
        {
            var gems = new int[5];
            for (int i = 0, v = h; i < 5; i++, v /= 7) gems[i] = v % 7;
            var hand = GemHand.Classify(gems);
            counts[hand] = counts.GetValueOrDefault(hand) + 1;
        }

        var gem = new StringBuilder(Head("Gem Hand", "Five gems, each the round's float × 7, floored: one of 7 colours with equal chance, so all 16,807 hands are equally likely. Each is classified and paid by the table below."));
        gem.AppendLine("| hand | hands of 16,807 | pays | RTP share |").AppendLine("|---|---|---|---|");
        double gRtp = 0;
        foreach (var (hand, bp) in GemHand.Pays)
        {
            var share = counts.GetValueOrDefault(hand) / 16_807.0 * bp / Mult.One;
            gRtp += share;
            gem.AppendLine(CultureInfo.InvariantCulture, $"| {hand} | {counts.GetValueOrDefault(hand):N0} | {X(bp)} | {share:P4} |");
        }

        gem.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"**RTP {gRtp:P4}** (stated {new GemHand().Rtp:F2}%).");
        File.WriteAllText($"{dir}/gem-hand.md", gem.ToString());
        ok &= gRtp <= 0.96 + 1e-12;

        // Baccarat: every rank combination of the six cards (13^6), each equally likely, through the production deal.
        var won = new Dictionary<string, double> { ["player"] = 0, ["banker"] = 0, ["tie"] = 0 };
        var f6 = new double[6];
        for (var c = 0; c < 4_826_809; c++)
        {
            for (int i = 0, v = c; i < 6; i++, v /= 13) f6[i] = ((v % 13) + 0.5) / 52;
            won[Baccarat.Deal(f6).Winner]++;
        }

        var bac = new StringBuilder(Head("Baccarat", "Punto banco with the standard drawing rules, dealt from an endless shoe: each card is the round's float × 52, floored (rank = card mod 13 + 1; tens and pictures count 0). All 13^6 = 4,826,809 rank combinations of the six cards are equally likely and are dealt through the production code."));
        bac.AppendLine("| bet | pays | wins | ties (stake back) | RTP |").AppendLine("|---|---|---|---|---|");
        var total = 4_826_809.0;
        foreach (var bet in new[] { "player", "banker", "tie" })
        {
            var pw = won[bet] / total;
            var push = bet == "tie" ? 0 : won["tie"] / total;
            var rtp = pw * Baccarat.WinBp[bet] / Mult.One + push;
            bac.AppendLine(CultureInfo.InvariantCulture, $"| {bet} | {X(Baccarat.WinBp[bet])} | {pw:P4} | {push:P4} | {rtp:P4} |");
        }

        bac.AppendLine().AppendLine("Baccarat keeps the standard pays (Player 1:1, Banker 0.95:1, Tie 8:1), so each bet's RTP is the game's own, stated per bet in the rules.");
        File.WriteAllText($"{dir}/baccarat.md", bac.ToString());

        // Higher or Lower: a strategy's RTP is P(its guesses all win) × the multiplier; the multiplier is the inverse of that chance × 0.96, floored.
        var hl = new StringBuilder(Head("Higher or Lower", "Cards from an endless deck: each is the round's float × 52, floored (rank = card mod 13 + 1, Ace low). A guess of higher-or-same on rank r wins with 14 − r ranks of 13; lower-or-same with r. After winning guesses with counts c₁ … c_k the multiplier is 0.96 × 13^k ÷ (c₁ × … × c_k), floored to 0.0001×, which is 0.96 ÷ P(all k win). Skips change nothing. A guess that cannot lose, or whose win would pass 5,000×, is refused."));
        double hLo = 1, hHi = 0;
        for (var a = 1; a <= 12; a++)
        {
            for (var b = 0; b <= 12; b++)
            {
                List<int> seq = b == 0 ? [a] : [a, b];
                var p = seq.Aggregate(1.0, (acc, c) => acc * c / 13.0);
                var rtp = p * HigherLower.MultiplierBp(seq) / Mult.One;
                hLo = Math.Min(hLo, rtp); hHi = Math.Max(hHi, rtp);
            }
        }

        hl.AppendLine(CultureInfo.InvariantCulture, $"A player who cashes out after any sequence of winning guesses gets RTP = P × floor(0.96 ÷ P × 10,000) ÷ 10,000, which is at most 96% and loses less than 0.0001 × P to the flooring. Over every sequence of one or two guesses the RTP is between {hLo:P4} and {hHi:P4}; longer sequences are the same bound.");
        File.WriteAllText($"{dir}/higher-lower.md", hl.ToString());
        ok &= hHi <= 0.96 + 1e-12;

        Console.WriteLine($"wrote sunburst-wheel, coin-flip, lucky-scratch, gem-hand, baccarat, higher-lower{(ok ? "" : "  CHECK FAILED")}");
        return ok ? 0 : 1;
    }
}
