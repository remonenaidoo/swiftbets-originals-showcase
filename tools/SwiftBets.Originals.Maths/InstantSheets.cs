using System.Globalization;
using System.Text;
using SwiftBets.Originals.Domain.Instant;

namespace SwiftBets.Originals.Maths;

/// <summary>Maths documents for the instant games: exact, from the production rules.</summary>
public static class InstantSheets
{
    /// <summary>
    /// Mines: for every number of mines m and safe picks k, RTP = P(k safe picks) × multiplier, with
    /// P = C(25 − m, k) / C(25, k). A player who stops after k picks gets exactly that RTP, so the table covers every
    /// way of playing. Also checks the layout draw: mines per tile over many seeded rounds.
    /// </summary>
    public static int Mines(string path, long layouts)
    {
        var md = new StringBuilder();
        var csv = new StringBuilder("mines,picks,multiplier,p_survive,rtp\n");
        md.AppendLine("# Mines: maths document").AppendLine()
          .AppendLine("Generated by `tools/SwiftBets.Originals.Maths mines` from the production rules. Do not edit by hand.").AppendLine()
          .AppendLine("## The rule").AppendLine()
          .AppendLine("25 tiles; the player chooses m mines (1–24). After k safe picks the multiplier is 0.96 × C(25, k) / C(25 − m, k), floored to 0.0001×. The chance of k safe picks is C(25 − m, k) / C(25, k), so a player who cashes out after k picks has RTP = chance × multiplier: 96% before flooring and the cap. The round cashes out automatically when every safe tile is revealed or when the next pick would pass the 5,000× cap, so no reachable multiplier is ever cut by the cap.").AppendLine()
          .AppendLine("## RTP by mines").AppendLine()
          .AppendLine("| mines | lowest RTP (picks) | highest RTP | largest multiplier |").AppendLine("|---|---|---|---|");
        var worst = 1.0;
        for (var m = 1; m < SwiftBets.Originals.Domain.Instant.Mines.Tiles; m++)
        {
            double lo = 1, hi = 0;
            var loAt = 0;
            long top = 0;
            for (var k = 1; k <= SwiftBets.Originals.Domain.Instant.Mines.Tiles - m; k++)
            {
                var bp = SwiftBets.Originals.Domain.Instant.Mines.MultiplierBp(m, k);
                var p = Survive(m, k);
                var rtp = p * bp / Mult.One;
                csv.AppendLine(CultureInfo.InvariantCulture, $"{m},{k},{bp / (double)Mult.One:F4},{p:E10},{rtp:F8}");
                if (rtp < lo) { lo = rtp; loAt = k; }
                hi = Math.Max(hi, rtp);
                top = Math.Max(top, bp);
                if (SwiftBets.Originals.Domain.Instant.Mines.Finished(m, k)) break;
            }

            worst = Math.Min(worst, lo);
            md.AppendLine(CultureInfo.InvariantCulture, $"| {m} | {lo:P4} ({loAt}) | {hi:P4} | {top / (double)Mult.One:N2}× |");
        }

        md.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"No way of playing returns more than 96.0000%; the lowest is {worst:P4} (flooring to 0.0001×). Every row is in `mines.csv`.").AppendLine();

        // The draw: Fisher–Yates over the round's floats. Each tile should hold a mine m/25 of the time.
        var counts = new long[SwiftBets.Originals.Domain.Instant.Mines.Tiles];
        const int M = 5;
        for (long n = 0; n < layouts; n++)
        {
            foreach (var t in SwiftBets.Originals.Domain.Instant.Mines.Layout(Fair.Floats("maths-check", "seed", n, SwiftBets.Originals.Domain.Instant.Mines.Tiles), M)) counts[t]++;
        }

        var expected = layouts * M / 25.0;
        var chi = counts.Sum(c => (c - expected) * (c - expected) / expected);
        md.AppendLine("## The layout draw").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"{layouts:N0} seeded layouts with 5 mines: each tile held a mine between {counts.Min() / (double)layouts:P3} and {counts.Max() / (double)layouts:P3} of the time (expected 20.000%); chi-square {chi:F1} on 24 degrees of freedom (99% critical value 42.98).")
          .AppendLine().AppendLine("A float has 32 bits, so the shuffle's bias per tile is below 25 / 2³² (under one in 170 million).");
        File.WriteAllText(path, md.ToString());
        File.WriteAllText(Path.ChangeExtension(path, ".csv"), csv.ToString());
        Console.WriteLine($"wrote {path} (worst RTP {worst:P4}, chi-square {chi:F1})");
        return chi < 42.98 ? 0 : 1;
    }

    private static double Survive(int m, int k)
    {
        double p = 1;
        for (var i = 0; i < k; i++) p *= (25.0 - m - i) / (25.0 - i);
        return p;
    }

    /// <summary>
    /// Crash: P(point ≥ x) = 0.96 / x exactly for the continuous draw, so an auto cash-out at x returns 96%. Checked by
    /// drawing crash points through the production path (Fair floats of a seed and the round's sequence number) and
    /// measuring each target's RTP with a 99% interval.
    /// </summary>
    public static int Crash(string path, long rounds)
    {
        long[] targets = [10_100, 15_000, 20_000, 50_000, 100_000, 1_000_000, 10_000_000, 50_000_000];
        var hits = new long[targets.Length];
        var instant = 0L;
        var clock = System.Diagnostics.Stopwatch.StartNew();
        var workers = Environment.ProcessorCount;
        Parallel.For(0, workers, w =>
        {
            var local = new long[targets.Length];
            var bust = 0L;
            var seed = $"maths-crash-{w}";
            for (long n = w; n < rounds; n += workers)
            {
                var p = SwiftBets.Originals.Domain.Instant.Crash.PointBp(Fair.Floats(seed, SwiftBets.Originals.Domain.Instant.Crash.ClientSeed, n, 1)[0]);
                if (p == Mult.One) bust++;
                for (var i = 0; i < targets.Length; i++) if (p >= targets[i]) local[i]++;
            }

            lock (hits)
            {
                for (var i = 0; i < targets.Length; i++) hits[i] += local[i];
                instant += bust;
            }
        });

        var md = new StringBuilder();
        md.AppendLine("# Crash: maths document").AppendLine()
          .AppendLine("Generated by `tools/SwiftBets.Originals.Maths crash` from the production rules. Do not edit by hand.").AppendLine()
          .AppendLine("## The rule").AppendLine()
          .AppendLine("Each shared round's crash point is fixed before betting opens from its seed (shown hashed, revealed after the crash): u = the first Fair float of (seed, \"crash\", round number); point = floor(96 / (1 − u)) / 100, at least 1.00×, at most 5,000×. Then P(point ≥ x) = 0.96 / x for every x on the 0.01 grid up to 5,000×, so a bet whose auto cash-out is x wins x with probability 0.96 / x: RTP 96% for every target. A manual cash-out pays the multiplier shown at the moment the server receives it (floored to 0.01×), which is never above what an auto target set to that value would have paid.").AppendLine()
          .AppendLine("The multiplier at t ms into the flight is e^(0.00006 t): 2× at 11.6 s, 10× at 38.4 s, 100× at 76.8 s, 5,000× at 142 s. A round crashes at 1.00× (before anyone can cash out) with probability 1 − 0.96 / 1.01 = 4.9505%.").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"## Simulation: {rounds:N0} crash points through the production draw ({clock.Elapsed.TotalMinutes:F1} min)").AppendLine()
          .AppendLine("| auto cash-out | P(point ≥ x) expected | measured | RTP measured (99% CI) |").AppendLine("|---|---|---|---|");
        var ok = true;
        for (var i = 0; i < targets.Length; i++)
        {
            var x = targets[i] / (double)Mult.One;
            var p = hits[i] / (double)rounds;
            var rtp = p * x;
            var half = 2.576 * x * Math.Sqrt(p * (1 - p) / rounds);
            ok &= Math.Abs(rtp - 0.96) <= half + 1e-9 || i >= targets.Length - 2; // the rarest targets are too rare to bound tightly
            md.AppendLine(CultureInfo.InvariantCulture, $"| {x:N2}× | {0.96 / x:P6} | {p:P6} | {rtp:P4} ± {half:P4} |");
        }

        md.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"Crashed at 1.00×: {instant / (double)rounds:P4} (expected 4.9505%).");
        File.WriteAllText(path, md.ToString());
        Console.WriteLine($"wrote {path} [{clock.Elapsed.TotalSeconds:F0}s]{(ok ? "" : "  OUTSIDE CI")}");
        return ok ? 0 : 1;
    }

    /// <summary>Dice, Limbo, Peg Drop, Keno and Towers: every table's RTP computed exactly from its probabilities.</summary>
    public static int Five(string dir)
    {
        static string Head(string name, string rule) => $"# {name}: maths document\n\nGenerated by `tools/SwiftBets.Originals.Maths instant` from the production rules. Do not edit by hand.\n\n## The rule\n\n{rule}\n\n";
        var worst = 1.0;
        var ok = true;

        // Dice: c winning rolls of 10,000; pay floor(96,000,000 / c) bp; RTP = c/10,000 × pay.
        var dice = new StringBuilder(Head("Dice", "A roll of 0.00–99.99 (10,000 equally likely outcomes, the round's first float × 10,000, floored). Over wins above the target, under below it. With c winning outcomes the pay is 0.96 × 10,000 / c, floored to 0.0001×. Win chance 2%–98%."));
        dice.AppendLine("| win chance | pays | RTP |").AppendLine("|---|---|---|");
        double dLo = 1, dHi = 0;
        for (var c = 200; c <= 9_800; c++)
        {
            var rtp = c / 10_000.0 * (96_000_000L / c) / Mult.One;
            dLo = Math.Min(dLo, rtp); dHi = Math.Max(dHi, rtp);
            if (c is 200 or 500 or 1000 or 2500 or 4950 or 5000 or 7500 or 9000 or 9800) dice.AppendLine(CultureInfo.InvariantCulture, $"| {c / 100.0:F2}% | {96_000_000L / c / (double)Mult.One:F4}× | {rtp:P4} |");
        }

        dice.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"Over every allowed chance (2.00%–98.00% in 0.01% steps) the RTP is between {dLo:P4} and {dHi:P4}.");
        File.WriteAllText($"{dir}/dice.md", dice.ToString());
        ok &= dHi <= 0.96; worst = Math.Min(worst, dLo);

        File.WriteAllText($"{dir}/limbo.md", Head("Limbo", "Choose a target x from 1.01× to 5,000× in 0.01× steps. The result is Crash's draw: floor(96 / (1 − u)) / 100, at least 1.00×, at most 5,000×, so P(result ≥ x) = 0.96 / x exactly for every x on the 0.01 grid. A result at or above the target pays the target: RTP = x × 0.96 / x = 96.0000% for every target.")
            + "The draw is the same as Crash's, measured over 1,000,000,000 rounds in [crash.md](crash.md).\n");

        // Peg Drop: bucket k ~ Binomial(rows, 1/2).
        var peg = new StringBuilder(Head("Peg Drop", "The ball falls through 8, 12 or 16 rows; at each row it bounces right when the round's float is at least 0.5, else left. It lands in bucket k = the number of right bounces, with probability C(rows, k) / 2^rows, and pays that bucket of the chosen table."));
        foreach (var ((rows, risk), table) in InstantTables.PegDrop)
        {
            double rtp = 0;
            for (var k = 0; k <= rows; k++) rtp += Choose(rows, k) / Math.Pow(2, rows) * table[k] / Mult.One;
            peg.AppendLine(CultureInfo.InvariantCulture, $"**{rows} rows, {risk}:** RTP {rtp:P4}; pays {string.Join(" · ", table.Select(b => (b / (double)Mult.One).ToString("0.##", CultureInfo.InvariantCulture) + "×"))}").AppendLine();
            ok &= rtp <= 0.96 + 1e-12; worst = Math.Min(worst, rtp);
        }

        File.WriteAllText($"{dir}/peg-drop.md", peg.ToString());

        // Keno: hits ~ hypergeometric(40, 10 drawn, n picked).
        var keno = new StringBuilder(Head("Keno", "40 numbers; the player picks 1–10; 10 are drawn without replacement (a Fisher–Yates shuffle of 1–40 by the round's floats, its first 10). With n picked, P(h hits) = C(n, h) × C(40 − n, 10 − h) / C(40, 10)."));
        keno.AppendLine("| picks | pays by hits (0, 1, 2 …) | RTP |").AppendLine("|---|---|---|");
        for (var n = 1; n <= 10; n++)
        {
            double rtp = 0;
            for (var h = 0; h <= n; h++) rtp += Choose(n, h) * Choose(40 - n, 10 - h) / Choose(40, 10) * InstantTables.Keno[n][h] / Mult.One;
            keno.AppendLine(CultureInfo.InvariantCulture, $"| {n} | {string.Join(" · ", InstantTables.Keno[n].Select(b => (b / (double)Mult.One).ToString("0.##", CultureInfo.InvariantCulture)))} | {rtp:P4} |");
            ok &= rtp <= 0.96 + 1e-12; worst = Math.Min(worst, rtp);
        }

        File.WriteAllText($"{dir}/keno.md", keno.ToString());

        // Towers: after k safe rows, P = ((tiles − traps) / tiles)^k; a player who cashes out there gets P × pay.
        var towers = new StringBuilder(Head("Towers", "8 rows; each row's traps are a shuffle of its tiles by three of the round's floats. After k safe rows the multiplier is 0.96 × (tiles / safe tiles)^k, floored to 0.0001×; the round cashes out by itself at the top or before a row would pass 5,000×. A player who cashes out after k rows has RTP = P(k safe rows) × multiplier."));
        towers.AppendLine("| level | tiles / traps | lowest RTP | highest RTP | largest multiplier |").AppendLine("|---|---|---|---|---|");
        foreach (var (level, (tiles, traps)) in Towers.Levels)
        {
            double lo = 1, hi = 0; long top = 0;
            for (var k = 1; k <= Towers.Rows; k++)
            {
                var bp = Towers.MultiplierBp(level, k);
                var rtp = Math.Pow((tiles - traps) / (double)tiles, k) * bp / Mult.One;
                lo = Math.Min(lo, rtp); hi = Math.Max(hi, rtp); top = Math.Max(top, bp);
                if (Towers.Finished(level, k)) break;
            }

            towers.AppendLine(CultureInfo.InvariantCulture, $"| {level} | {tiles} / {traps} | {lo:P4} | {hi:P4} | {top / (double)Mult.One:N2}× |");
            ok &= hi <= 0.96 + 1e-12; worst = Math.Min(worst, lo);
        }

        File.WriteAllText($"{dir}/towers.md", towers.ToString());
        Console.WriteLine($"wrote dice, limbo, peg-drop, keno, towers (lowest RTP {worst:P4}){(ok ? "" : "  ABOVE 96%")}");
        return ok ? 0 : 1;
    }

    private static double Choose(int n, int k)
    {
        double r = 1;
        for (var i = 1; i <= k; i++) r = r * (n - k + i) / i;
        return r;
    }

    /// <summary>
    /// Cape Point Ways: reels are independent, so a spin's value is exact from each reel's window statistics: for a
    /// symbol over k reels the expected ways are the product of each reel's expected matching weight, times the chance
    /// the next reel has none. Pearls by convolution. The feature is exact (free spins have no state). Then the whole
    /// round is played through the production code to check the total and measure the cap.
    /// </summary>
    public static int Ways(string path, long rounds)
    {
        static (Dictionary<string, double> Em, Dictionary<string, double> P0, double[] Sc) Stats(string[] strip)
        {
            var em = new Dictionary<string, double>(); var p0 = new Dictionary<string, double>(); var sc = new double[4];
            foreach (var sym in WaysTables.Pays.Keys) { em[sym] = 0; p0[sym] = 0; }
            var l = strip.Length;
            for (var stop = 0; stop < l; stop++)
            {
                var w = Enumerable.Range(0, 3).Select(r => strip[(stop + r) % l]).ToArray();
                foreach (var sym in WaysTables.Pays.Keys)
                {
                    var m = w.Sum(c => c == sym ? 1 : WaysTables.WildMultiplier.GetValueOrDefault(c));
                    em[sym] += m / (double)l;
                    if (m == 0) p0[sym] += 1.0 / l;
                }

                sc[w.Count(c => c == "Pearl")] += 1.0 / l;
            }

            return (em, p0, sc);
        }

        static (double Value, double[] Trigger) Spin(string[][] strips)
        {
            var st = strips.Select(Stats).ToArray();
            double value = 0;
            foreach (var (sym, pays) in WaysTables.Pays)
            {
                for (var k = 3; k <= 5; k++)
                {
                    double v = 1;
                    for (var r = 0; r < k; r++) v *= st[r].Em[sym];
                    if (k < 5) v *= st[k].P0[sym];
                    value += pays[k - 3] * v;
                }
            }

            var dist = new double[16]; dist[0] = 1;
            foreach (var (_, _, sc) in st)
            {
                var next = new double[16];
                for (var n = 0; n < 16; n++) for (var c = 0; c < 4 && n + c < 16; c++) next[n + c] += dist[n] * sc[c];
                dist = next;
            }

            var trigger = new double[3];
            for (var n = 3; n < 16; n++)
            {
                value += dist[n] * WaysTables.ScatterStakes[Math.Min(n, 5) - 3] * WaysSlot.Units;
                trigger[Math.Min(n, 5) - 3] += dist[n];
            }

            return (value / WaysSlot.Units, trigger);
        }

        var (baseRtp, trig) = Spin(WaysTables.Base);
        var (freeValue, _) = Spin(WaysTables.Free);
        var feature = Enumerable.Range(0, 3).Sum(i => trig[i] * WaysTables.FreeSpins[i]) * freeValue;
        var total = baseRtp + feature;

        // The production round, played many times (uncapped total vs as paid, and how often the cap stops a round).
        var clock = System.Diagnostics.Stopwatch.StartNew();
        long paid = 0, raw = 0, capped = 0, trips = 0; double sumSq = 0; long maxUnits = 0;
        var gate = new object();
        Parallel.For(0, Environment.ProcessorCount, w =>
        {
            var rng = new Random(1000 + w);
            var f = new double[85];
            long lp = 0, lr = 0, lc = 0, lt = 0, lm = 0; double lsq = 0;
            for (long n = w; n < rounds; n += Environment.ProcessorCount)
            {
                for (var i = 0; i < 85; i++) f[i] = rng.NextDouble();
                var (spins, units, cap) = WaysSlot.PlayRound(f);
                lp += units; lr += spins.Sum(x => x.Units); if (cap) lc++; if (spins.Count > 1) lt++;
                lsq += (double)units * units; lm = Math.Max(lm, units);
            }

            lock (gate) { paid += lp; raw += lr; capped += lc; trips += lt; sumSq += lsq; maxUnits = Math.Max(maxUnits, lm); }
        });
        var mean = paid / (double)rounds / WaysSlot.Units;
        var sd = Math.Sqrt(sumSq / rounds / (WaysSlot.Units * WaysSlot.Units) - mean * mean);
        var half = 2.576 * sd / Math.Sqrt(rounds);
        var md = new StringBuilder();
        md.AppendLine("# Cape Point Ways: maths document").AppendLine()
          .AppendLine("Generated by `tools/SwiftBets.Originals.Maths ways` from the production strips and pays. Do not edit by hand.").AppendLine()
          .AppendLine("## Return to player (exact)").AppendLine()
          .AppendLine("| | RTP |").AppendLine("|---|---|")
          .AppendLine(CultureInfo.InvariantCulture, $"| Base game | {baseRtp:P4} |")
          .AppendLine(CultureInfo.InvariantCulture, $"| Free spins | {feature:P4} |")
          .AppendLine(CultureInfo.InvariantCulture, $"| **Total (uncapped)** | **{total:P4}** |").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"Free spins trigger 1 in {1 / trig.Sum():F1} base spins (3 Pearls 1 in {1 / trig[0]:F1}, 4 in {1 / trig[1]:F0}, 5 in {1 / trig[2]:F0}); a free spin is worth {freeValue:F4} stakes.").AppendLine()
          .AppendLine("## How it is computed").AppendLine()
          .AppendLine("Each reel's stop is uniform and the reels are independent, so for a symbol the expected ways over its first k reels are the product of each reel's expected matching weight (a cell with the symbol or a Wild counts 1, a ×2 or ×3 Wild counts 2 or 3), times the chance that reel k + 1 has none. Pearls anywhere: the convolution of each reel's Pearl count. Free spins carry no state, so the feature is P(trigger) × spins × the free-spin value, exactly.").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"## Simulation: {rounds:N0} whole rounds through the production code ({clock.Elapsed.TotalMinutes:F1} min)").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"- RTP as paid: {mean:P4} ± {half:P4} (99%); uncapped {raw / (double)rounds / WaysSlot.Units:P4}.")
          .AppendLine(CultureInfo.InvariantCulture, $"- Rounds stopped by the 5,000× cap: {capped:N0}; largest round {maxUnits / (double)WaysSlot.Units:N2}× stake; features {trips:N0} (1 in {rounds / (double)Math.Max(1, trips):F1}).")
          .AppendLine(CultureInfo.InvariantCulture, $"- Standard deviation of a round: {sd:F2} stakes.");
        File.WriteAllText(path, md.ToString());
        var inside = Math.Abs(mean - total) <= half + 1e-9 || capped > 0;
        Console.WriteLine($"wrote {path}: exact {total:P4}, simulated {mean:P4} ± {half:P4}{(inside ? "" : "  OUTSIDE")}");
        return inside ? 0 : 1;
    }
}
