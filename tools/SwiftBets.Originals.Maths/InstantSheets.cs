using System.Globalization;
using System.Text;
using SwiftBets.Originals.Domain.Instant;

namespace SwiftBets.Originals.Maths;

/// <summary>Maths documents for the instant games: exact, from the production rules.</summary>
public static class InstantSheets
{
    /// <summary>
    /// Mines: for every number of mines m and safe picks k, RTP = P(k safe picks) × multiplier, with
    /// P = C(25 − m, k) / C(25, k). A player who stops after k picks gets exactly that RTP, so the table covers every
    /// way of playing. Also checks the layout draw: mines per tile over many seeded rounds.
    /// </summary>
    public static int Mines(string path, long layouts)
    {
        var md = new StringBuilder();
        var csv = new StringBuilder("mines,picks,multiplier,p_survive,rtp\n");
        md.AppendLine("# Mines: maths document").AppendLine()
          .AppendLine("Generated by `tools/SwiftBets.Originals.Maths mines` from the production rules. Do not edit by hand.").AppendLine()
          .AppendLine("## The rule").AppendLine()
          .AppendLine("25 tiles; the player chooses m mines (1–24). After k safe picks the multiplier is 0.96 × C(25, k) / C(25 − m, k), floored to 0.0001×. The chance of k safe picks is C(25 − m, k) / C(25, k), so a player who cashes out after k picks has RTP = chance × multiplier: 96% before flooring and the cap. The round cashes out automatically when every safe tile is revealed or when the next pick would pass the 5,000× cap, so no reachable multiplier is ever cut by the cap.").AppendLine()
          .AppendLine("## RTP by mines").AppendLine()
          .AppendLine("| mines | lowest RTP (picks) | highest RTP | largest multiplier |").AppendLine("|---|---|---|---|");
        var worst = 1.0;
        for (var m = 1; m < SwiftBets.Originals.Domain.Instant.Mines.Tiles; m++)
        {
            double lo = 1, hi = 0;
            var loAt = 0;
            long top = 0;
            for (var k = 1; k <= SwiftBets.Originals.Domain.Instant.Mines.Tiles - m; k++)
            {
                var bp = SwiftBets.Originals.Domain.Instant.Mines.MultiplierBp(m, k);
                var p = Survive(m, k);
                var rtp = p * bp / Mult.One;
                csv.AppendLine(CultureInfo.InvariantCulture, $"{m},{k},{bp / (double)Mult.One:F4},{p:E10},{rtp:F8}");
                if (rtp < lo) { lo = rtp; loAt = k; }
                hi = Math.Max(hi, rtp);
                top = Math.Max(top, bp);
                if (SwiftBets.Originals.Domain.Instant.Mines.Finished(m, k)) break;
            }

            worst = Math.Min(worst, lo);
            md.AppendLine(CultureInfo.InvariantCulture, $"| {m} | {lo:P4} ({loAt}) | {hi:P4} | {top / (double)Mult.One:N2}× |");
        }

        md.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"No way of playing returns more than 96.0000%; the lowest is {worst:P4} (flooring to 0.0001×). Every row is in `mines.csv`.").AppendLine();

        // The draw: Fisher–Yates over the round's floats. Each tile should hold a mine m/25 of the time.
        var counts = new long[SwiftBets.Originals.Domain.Instant.Mines.Tiles];
        const int M = 5;
        for (long n = 0; n < layouts; n++)
        {
            foreach (var t in SwiftBets.Originals.Domain.Instant.Mines.Layout(Fair.Floats("maths-check", "seed", n, SwiftBets.Originals.Domain.Instant.Mines.Tiles), M)) counts[t]++;
        }

        var expected = layouts * M / 25.0;
        var chi = counts.Sum(c => (c - expected) * (c - expected) / expected);
        md.AppendLine("## The layout draw").AppendLine()
          .AppendLine(CultureInfo.InvariantCulture, $"{layouts:N0} seeded layouts with 5 mines: each tile held a mine between {counts.Min() / (double)layouts:P3} and {counts.Max() / (double)layouts:P3} of the time (expected 20.000%); chi-square {chi:F1} on 24 degrees of freedom (99% critical value 42.98).")
          .AppendLine().AppendLine("A float has 32 bits, so the shuffle's bias per tile is below 25 / 2³² (under one in 170 million).");
        File.WriteAllText(path, md.ToString());
        File.WriteAllText(Path.ChangeExtension(path, ".csv"), csv.ToString());
        Console.WriteLine($"wrote {path} (worst RTP {worst:P4}, chi-square {chi:F1})");
        return chi < 42.98 ? 0 : 1;
    }

    private static double Survive(int m, int k)
    {
        double p = 1;
        for (var i = 0; i < k; i++) p *= (25.0 - m - i) / (25.0 - i);
        return p;
    }
}
