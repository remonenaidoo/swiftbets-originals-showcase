    /// <summary>
    /// Kalahari Gem Fall: tumbles chain, so the RTP is measured by playing whole rounds through the production code,
    /// split into base and free spins, with a 99% interval. <paramref name="cfg"/> lets the tuner try other values.
    /// </summary>
    public static (double Base, double Free, double Total, double Half, double Hit, double Trigger, long Capped, double Max, double Sd) Cascade(CascadeConfig cfg, long rounds)
    {
        long b = 0, fr = 0, hits = 0, trips = 0, capped = 0, max = 0; double sq = 0;
        var gate = new object();
        Parallel.For(0, Environment.ProcessorCount, w =>
        {
            var rng = new Random(3000 + w);
            var f = new double[CascadeSlot.Floats];
            long lb = 0, lf = 0, lh = 0, lt = 0, lc = 0, lm = 0; double lsq = 0;
            for (long n = w; n < rounds; n += Environment.ProcessorCount)
            {
                for (var i = 0; i < 64; i++) f[i] = rng.NextDouble();
                var (spins, units, cap) = CascadeSlot.PlayRound(cfg, new Lazy64(f, rng));
                var baseUnits = Math.Min(spins[0].Units, CascadeSlot.CapUnits);
                lb += baseUnits; lf += units - baseUnits;
                if (spins[0].Units > 0) lh++;
                if (spins.Count > 1) lt++;
                if (cap) lc++;
                lm = Math.Max(lm, units); lsq += (double)units * units;
            }

            lock (gate) { b += lb; fr += lf; hits += lh; trips += lt; capped += lc; max = Math.Max(max, lm); sq += lsq; }
        });
        var u = (double)CascadeSlot.Units;
        var mean = (b + fr) / (double)rounds / u;
        var sd = Math.Sqrt(sq / rounds / (u * u) - mean * mean);
        return (b / (double)rounds / u, fr / (double)rounds / u, mean, 2.576 * sd / Math.Sqrt(rounds), hits / (double)rounds, trips / (double)rounds, capped, max / u, sd);
    }

